"""以單一擁有者能力快照提供伺服器端草稿規劃服務。

公開範圍：提供整合權限查詢、規劃器與草稿保存服務的 ``伺服器端草稿規劃服務``。
例外：公開操作可能拋出 ``授權選擇錯誤``、``規劃器輸出無效`` 或 ``規劃器不可用``。
副作用：匯入只建立類別；建立草稿時會查詢權限、呼叫規劃器並保存草稿。
"""
from __future__ import annotations

from dataclasses import dataclass

from ..協定 import Planner權限查詢, 規劃權限快照, 安全查詢規劃權限
from .權限協調 import 授權選擇錯誤, 權限協調器
from .綱要 import 規劃服務, 規劃草稿
from .規劃器契約 import (
    建立規劃器輸入, 規劃器不可用, 規劃器轉接器, 規劃器輸出無效,
    驗證規劃器輸出, 驗證選擇,
)

@dataclass(frozen=True, slots=True)
class _固定快照查詢:
    """重播同一次已分離的權威快照，而不回查擁有者供應商。

    欄位：``快照`` 是建構時保存的 ``規劃權限快照``。
    回傳：建構後得到不可變查詢物件；查詢永遠回傳該快照。
    例外：建構與查詢不主動拋出業務例外。
    副作用：不回查供應商，無外部副作用。
    """
    快照: 規劃權限快照

    def 查詢規劃權限(self, 擁有者識別碼: str, /) -> 規劃權限快照:
        """回傳建構時固定的規劃權限快照。

        參數：``擁有者識別碼`` 為協定要求但刻意不使用，因快照已綁定同一擁有者。
        回傳：保存的 ``規劃權限快照``。
        例外：無。
        副作用：不回查權限供應商，無外部副作用。
        """
        return self.快照

class 伺服器端草稿規劃服務:
    """由客戶端意圖與單一權威快照建立伺服器端草稿。

    建構依賴：權限查詢、規劃器轉接器及可選草稿服務。
    回傳：``建立草稿`` 回傳已保存的 ``規劃草稿``。
    例外：可能拋出授權、規劃器輸出或規劃器可用性例外。
    副作用：建立草稿時會查詢權限、呼叫規劃器並透過草稿服務保存草稿。
    """

    def __init__(self, 權限查詢: Planner權限查詢, 規劃器: 規劃器轉接器, *, 草稿服務: 規劃服務 | None = None) -> None:
        """保存規劃流程所需依賴。

        參數：``權限查詢`` 提供權威快照；``規劃器`` 產生候選內容；``草稿服務`` 可覆寫預設保存服務。
        回傳：無回傳值。
        例外：建立預設 ``規劃服務`` 時的例外會原樣傳遞。
        副作用：保存依賴；未提供 ``草稿服務`` 時建立預設服務，但不查詢或持久化資料。
        """
        self._權限查詢 = 權限查詢
        self._規劃器 = 規劃器
        self._草稿服務 = 草稿服務 or 規劃服務()

    def 建立草稿(
        self, 擁有者識別碼: str, 原始需求: str, 選擇技能: tuple[str, ...],
        回應模式: str, *, 現在: float,
    ) -> 規劃草稿:
        """以同一快照驗證推薦工具並保存帶雜湊與修訂釘選的草稿。

        參數：``擁有者識別碼`` 指定權限主體；``原始需求`` 是需求文字；``選擇技能`` 是排序後技能；
        ``回應模式`` 是文字或結構化模式；``現在`` 是建立時間。
        回傳：草稿服務建立並保存的 ``規劃草稿``。
        例外：未授權選擇拋出 ``授權選擇錯誤``；輸出失效拋出 ``規劃器輸出無效``；
        供應商或其他安全失敗拋出 ``規劃器不可用``；控制流例外原樣傳遞。
        副作用：查詢一次權威快照、呼叫規劃器，並建立持久化草稿。
        """
        try:
            技能名稱, 模式 = 驗證選擇(選擇技能, 回應模式)
            快照 = 安全查詢規劃權限(self._權限查詢, 擁有者識別碼)
            技能對照 = {項目.名稱: 項目 for 項目 in 快照.技能}
            if any(名稱 not in 技能對照 for 名稱 in 技能名稱):
                raise 授權選擇錯誤("規劃能力未獲授權")
            選定技能 = tuple(技能對照[名稱] for 名稱 in 技能名稱)
            輸入 = 建立規劃器輸入(原始需求, 模式, 選定技能, 快照.工具)
            輸出 = 驗證規劃器輸出(self._規劃器.產生(輸入), 輸入)
            推薦 = set(輸出.建議工具)
            選定工具 = tuple(項目.名稱 for 項目 in 快照.工具 if 項目.名稱 in 推薦)
            if set(選定工具) != 推薦:
                raise 規劃器輸出無效("規劃器輸出無效")
            return self._草稿服務.建立授權草稿(
                權限協調器(_固定快照查詢(快照)), 擁有者識別碼, 原始需求,
                輸出.預覽, 技能名稱, 選定工具, 現在=現在,
            )
        except (KeyboardInterrupt, SystemExit, GeneratorExit):
            raise
        except (授權選擇錯誤, 規劃器輸出無效, 規劃器不可用):
            raise
        except BaseException:
            raise 規劃器不可用("規劃器暫時不可用") from None

__all__ = ["伺服器端草稿規劃服務"]
